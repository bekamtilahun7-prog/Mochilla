import { useState } from "react";
import { FileText, Clock, Play } from "lucide-react";
import { aiApi } from "../services/api";

export function QuizGenerator() {
  const [topic, setTopic] = useState("");
  const [quizResponse, setQuizResponse] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const handleGenerateQuiz = async () => {
    const trimmedTopic = topic.trim();

    if (!trimmedTopic) {
      setError("Please enter a topic or concept to generate a quiz.");
      return;
    }

    setError("");
    setLoading(true);
    setQuizResponse(null);

    try {
      const response = await aiApi.quiz({ topic: trimmedTopic });
      setQuizResponse(
        response.data.quiz ||
          "No quiz was generated. Please try another topic.",
      );
    } catch (err) {
      console.error("Quiz generation error:", err);
      setError("Unable to generate quiz at the moment. Please try again.");
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="p-8">
      <div className="max-w-3xl mx-auto space-y-6">
        <div>
          <h1 className="text-3xl font-bold text-[#1C1F2A] mb-2">
            Quiz Generator
          </h1>
          <p className="text-[#6B7280]">
            Create a quiz from a topic you are studying and get instant practice
            questions.
          </p>
        </div>

        <div className="bg-white rounded-2xl p-8 shadow-sm border border-gray-100">
          <div className="flex flex-col gap-4">
            <div>
              <label className="block text-sm font-medium text-[#1C1F2A] mb-2">
                Study topic or concept
              </label>
              <input
                type="text"
                value={topic}
                onChange={(e) => setTopic(e.target.value)}
                placeholder="e.g. Derivatives in calculus"
                className="w-full rounded-2xl border border-gray-200 px-4 py-3 bg-[#F7F9FC] focus:outline-none focus:ring-2 focus:ring-[#4A90E2]"
              />
            </div>

            {error && <p className="text-sm text-[#EF4444]">{error}</p>}

            <button
              onClick={handleGenerateQuiz}
              disabled={loading}
              className="w-full inline-flex items-center justify-center gap-2 rounded-2xl bg-gradient-to-r from-[#4A90E2] to-[#7C5CFF] px-6 py-3 text-white font-semibold hover:shadow-lg transition-all disabled:opacity-70"
            >
              <Play className="w-5 h-5" />
              {loading ? "Generating Quiz..." : "Generate Quiz"}
            </button>
          </div>
        </div>

        {quizResponse && (
          <div className="bg-white rounded-2xl p-8 shadow-sm border border-gray-100">
            <div className="flex items-center gap-3 mb-4">
              <div className="w-12 h-12 rounded-2xl bg-[#4A90E2]/10 flex items-center justify-center">
                <FileText className="w-6 h-6 text-[#4A90E2]" />
              </div>
              <div>
                <h2 className="text-xl font-bold text-[#1C1F2A]">
                  Your Generated Quiz
                </h2>
                <p className="text-sm text-[#6B7280]">
                  Review the questions generated by MOCHILA.
                </p>
              </div>
            </div>
            <div className="whitespace-pre-line text-[#1C1F2A] text-sm leading-7">
              {quizResponse}
            </div>
          </div>
        )}

        {!quizResponse && !loading && (
          <div className="bg-white rounded-2xl p-8 shadow-sm border border-gray-100 text-center">
            <Clock className="w-12 h-12 text-[#4A90E2] mx-auto mb-4" />
            <h2 className="text-xl font-semibold text-[#1C1F2A] mb-2">
              Ready to create a new quiz?
            </h2>
            <p className="text-[#6B7280]">
              Enter any academic topic and MOCHILA will generate a short quiz
              for practice.
            </p>
          </div>
        )}
      </div>
    </div>
  );
}
